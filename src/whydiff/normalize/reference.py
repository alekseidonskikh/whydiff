"""Reference implementation of normalization and hashing in pure Python.

The SQL generated by each dialect must produce exactly what these functions
produce. Tests use them as the oracle, and connectors without SQL (files,
dataframes) can use them directly.

Row encoding
------------
Each value is normalized to a string ``v`` and encoded as a token:

* ``NULL``      -> ``<<NULL>>`` (:data:`whydiff.constants.NULL_TOKEN`)
* otherwise     -> ``<byte length of v>:<v>``

Tokens are concatenated. Length prefixes make the encoding unambiguous, so
``('a|', 'b')`` and ``('a', '|b')`` never collide, and since a value token
always starts with a digit, the NULL token never collides with any value:
``NULL``, ``''`` and the string ``'<<NULL>>'`` all hash differently.

The row hash is the first 15 hex digits (60 bits) of ``md5(row)`` read as an
integer: it fits a signed BIGINT in every database, and sums of many of them
fit NUMERIC / HUGEINT.
"""

from __future__ import annotations

import datetime as dt
import hashlib
from collections.abc import Sequence
from decimal import ROUND_HALF_UP, Decimal
from typing import Any

from whydiff.constants import HASH_HEX_DIGITS, LENGTH_SEPARATOR, NULL_TOKEN
from whydiff.model import Column, TypeFamily
from whydiff.normalize.rules import NormalizationRules


def _fixed(value: Decimal, digits: int) -> str:
    if value.is_nan():
        return "NaN"
    if value.is_infinite():
        return "Infinity" if value > 0 else "-Infinity"
    quantum = Decimal(1).scaleb(-digits)
    result = value.quantize(quantum, rounding=ROUND_HALF_UP)
    if result.is_zero():
        result = abs(result)  # databases print 0.00, never -0.00
    return f"{result:f}"


def _timestamp(value: dt.datetime, precision: int) -> str:
    text = value.strftime("%Y-%m-%dT%H:%M:%S.%f")
    return text[:19] if precision == 0 else text[: 20 + precision]


def normalize_value(value: Any, column: Column, rules: NormalizationRules) -> str | None:
    """Return the canonical string for one value, or None for NULL."""
    if value is None:
        return None
    family = column.family
    if family is TypeFamily.INTEGER:
        return str(int(value))
    if family is TypeFamily.DECIMAL:
        return _fixed(Decimal(value), rules.decimal_digits(column.scale))
    if family is TypeFamily.FLOAT:
        return _fixed(Decimal(repr(float(value))), rules.float_digits)
    if family is TypeFamily.BOOLEAN:
        return "1" if value else "0"
    if family is TypeFamily.DATE:
        return value.isoformat() if isinstance(value, dt.date) else str(value)
    if family is TypeFamily.TIMESTAMP:
        return _timestamp(value, rules.timestamp_precision)
    if family is TypeFamily.TIMESTAMPTZ:
        utc = value.astimezone(dt.timezone.utc).replace(tzinfo=None)
        return _timestamp(utc, rules.timestamp_precision)
    text = str(value)
    if family is TypeFamily.TEXT:
        if rules.trim_strings:
            text = text.strip(" ")
        if rules.case_insensitive:
            text = text.lower()
    return text


def encode_token(normalized: str | None) -> str:
    if normalized is None:
        return NULL_TOKEN
    return f"{len(normalized.encode('utf-8'))}{LENGTH_SEPARATOR}{normalized}"


def hash_text(text: str) -> int:
    return int(hashlib.md5(text.encode("utf-8")).hexdigest()[:HASH_HEX_DIGITS], 16)


def hash_normalized(values: Sequence[str | None]) -> int:
    return hash_text("".join(encode_token(v) for v in values))


def row_hash(values: Sequence[Any], columns: Sequence[Column], rules: NormalizationRules) -> int:
    normalized = [normalize_value(v, c, rules) for v, c in zip(values, columns, strict=True)]
    return hash_normalized(normalized)
